// Printable BCF merchant account creation form — generated from the data TOBi collected (what is sent to G2).
import { get, all, j } from './db.js';
import { FIELDS, CONTRACT_TYPES, DOC_TYPES } from './schema.js';
import { appDocuments } from './documents.js';
import { fmtMsisdn } from './g2.js';

const esc = (v) => String(v ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const fmtVal = (k, v) => {
  if (v == null || v === '') return '';
  if (k === 'contract_type') return `${v} — ${CONTRACT_TYPES[v] || ''}`;
  if (k === 'legal_form') return v === 'COMPANY' ? 'Company (SARL, SA…)' : 'Individual establishment';
  if (k === 'access_channel') return { USSD: 'USSD', APP: 'M-Pesa App', INTEGRATED: 'Integrated solution (API)' }[v] || v;
  return v;
};

export function bcfHtml(application_id) {
  const app = get('SELECT * FROM applications WHERE id=?', application_id);
  if (!app) return null;
  const f = j(app.fields, {}), src = j(app.field_sources, {});
  const c = app.case_id ? get('SELECT * FROM cases WHERE id=?', app.case_id) : null;
  const g2 = c?.account_msisdn ? get('SELECT * FROM g2_accounts WHERE msisdn=?', c.account_msisdn) : null;
  const kyc = j(g2?.kyc, {});
  const req = c ? get('SELECT * FROM g2_requests WHERE case_ref=? ORDER BY id DESC', c.ref) : null;
  const docs = appDocuments(app.id);
  const sections = {};
  for (const fd of FIELDS) { if (!fd.req(f) && f[fd.key] == null) continue; (sections[fd.section] ||= []).push(fd); }
  const srcTag = (k) => { const s = src[k] || ''; return s.startsWith('document') ? '<span class="t d">document ✓</span>' : s ? '<span class="t c">declared</span>' : ''; };
  const rows = Object.entries(sections).map(([sec, fs]) => `<section><h3>${esc(sec)}</h3><table>${fs.map(fd => `<tr><th>${esc(fd.label)}</th><td>${esc(fmtVal(fd.key, f[fd.key]))}</td><td class="s">${srcTag(fd.key)}</td></tr>`).join('')}</table></section>`).join('');
  const now = new Date().toISOString().slice(0, 16).replace('T', ' ');
  return `<!doctype html><html><head><meta charset="utf-8"><title>BCF — ${esc(f.trading_name || f.legal_name || 'Merchant')}</title>
<style>
*{box-sizing:border-box}body{font-family:Inter,Arial,sans-serif;color:#1a1b1f;margin:0;background:#f4f5f7}
.page{max-width:900px;margin:24px auto;background:#fff;padding:36px 42px;box-shadow:0 4px 20px rgba(0,0,0,.08)}
header{display:flex;align-items:center;gap:16px;border-bottom:4px solid #e60000;padding-bottom:14px}
header .t1{font-size:22px;font-weight:800}header .t2{color:#6b707c;font-size:13px}
header img{height:46px}.ref{margin-left:auto;text-align:right;font-size:12px;color:#444}.ref b{font-size:15px;color:#1a1b1f}
.grid{display:grid;grid-template-columns:repeat(4,1fr);gap:10px;margin:18px 0}
.k{background:#f4f5f7;border-radius:8px;padding:10px 12px}.k small{display:block;font-size:10px;letter-spacing:.12em;color:#6b707c;font-weight:700}.k b{font-size:15px}
h3{font-size:12px;letter-spacing:.14em;text-transform:uppercase;color:#e60000;margin:22px 0 6px}
table{width:100%;border-collapse:collapse;font-size:13.5px}th{text-align:left;width:38%;color:#555;font-weight:600;padding:7px 8px;border-bottom:1px solid #eee}td{padding:7px 8px;border-bottom:1px solid #eee;font-weight:600}
td.s{width:110px;text-align:right}.t{font-size:10.5px;font-weight:700;padding:2px 7px;border-radius:10px}.t.d{background:#e3f6ec;color:#0a9d58}.t.c{background:#e8efff;color:#2563eb}
.sig{display:grid;grid-template-columns:1fr 1fr;gap:30px;margin-top:30px}.sig div{border-top:1px solid #999;padding-top:6px;font-size:12px;color:#555;height:70px}
.foot{margin-top:24px;font-size:11px;color:#888;border-top:1px solid #eee;padding-top:10px}
.btn{position:fixed;right:24px;top:20px;background:#e60000;color:#fff;border:0;border-radius:10px;padding:12px 18px;font-weight:800;cursor:pointer}
@media print{body{background:#fff}.page{box-shadow:none;margin:0;max-width:none}.btn{display:none}}
</style></head><body><button class="btn" onclick="window.print()">🖨 Print / Save as PDF</button><div class="page">
<header><img src="/logo_crop.png" onerror="this.style.display='none'"><div><div class="t1">Bulletin de Création — M-Pesa Business (Merchant)</div><div class="t2">Merchant account creation form · Vodacash S.A. · generated by SLA Sentinel AI from the TOBi conversation</div></div>
<div class="ref">Case<br><b>${esc(c?.ref || 'Draft')}</b><br>${esc(now)} UTC</div></header>
<div class="grid">
 <div class="k"><small>MERCHANT NUMBER</small><b>${esc(kyc.merchant_id || '— pending')}</b></div>
 <div class="k"><small>TILL NUMBER</small><b>${esc(g2?.till_number || '—')}</b></div>
 <div class="k"><small>MERCHANT SIM</small><b>${esc(kyc.merchant_sim ? fmtMsisdn(kyc.merchant_sim) : '—')}</b></div>
 <div class="k"><small>G2 REFERENCE</small><b>${esc(g2?.g2_ref || (req ? req.status : '—'))}</b></div>
</div>
${rows}
<section><h3>Supporting documents</h3><table>${docs.map(d => `<tr><th>${esc(DOC_TYPES[d.doc_type]?.label || d.doc_type)}</th><td>${esc(d.filename)}</td><td class="s">${d.expiry_date ? 'exp. ' + esc(d.expiry_date) : ''}</td></tr>`).join('') || '<tr><td>None</td></tr>'}</table></section>
<section><h3>Declaration</h3><p style="font-size:13px;line-height:1.5">The applicant certifies that the information provided is accurate and complete, accepts the M-Pesa merchant terms, the Vodacash AML/CFT policy (law n°22/068) and the processing of personal data for the purposes of this contract. Accepted in TOBi: <b>${esc(f.terms_accepted || '—')}</b>.</p></section>
<div class="sig"><div>Applicant — ${esc(f.representative_name || f.owner_name || '')}</div><div>Vodacash — Merchant Operations</div></div>
<div class="foot">Fields marked “document ✓” were read from the uploaded documents and cross-verified; “declared” fields come from the conversation. ${c?.sla_due ? 'SLA due ' + esc(c.sla_due.slice(0, 16).replace('T', ' ')) + ' UTC.' : ''}</div>
</div></body></html>`;
}
